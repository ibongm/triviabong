// Progress tracking for scripts/audit-category.mjs.
//
// The audit workflow checks a bounded number of questions per run, so it
// needs to remember which questions earlier runs already covered. Progress
// is keyed by question id (not array position), so questions added or
// removed between runs never shift what counts as "audited".
//
// Pure functions only (no fs) so they can be unit-tested; the script does the
// file I/O. The on-disk shape lives in audit/progress.json:
//   { version: 1,
//     categories: {
//       <category>: { complete, total, auditedIds: [...],
//                     runs: [{ runId, date, audited, modified, failedBatches, modifiedIds }] }
//     } }

export const PROGRESS_VERSION = 1;

const emptyCategory = () => ({ complete: false, total: 0, auditedIds: [], runs: [] });

/** Returns a clean progress object from whatever was read from disk (or null). */
export const normalizeProgress = (raw) => {
    const categories = {};
    const source = raw && typeof raw === 'object' && raw.categories ? raw.categories : {};
    for (const [key, value] of Object.entries(source)) {
        categories[key] = {
            ...emptyCategory(),
            ...value,
            auditedIds: Array.isArray(value?.auditedIds) ? [...value.auditedIds] : [],
            runs: Array.isArray(value?.runs) ? [...value.runs] : [],
        };
    }
    return { version: PROGRESS_VERSION, categories };
};

const auditedSetFor = (progress, category) =>
    new Set(progress?.categories?.[category]?.auditedIds || []);

/** Questions of `allQuestions` that no earlier run has audited, in file order. */
export const getUnaudited = (allQuestions, progress, category) => {
    const audited = auditedSetFor(progress, category);
    return allQuestions.filter((q) => !audited.has(q.id));
};

/**
 * The next questions to audit: up to `max` unaudited ones in file order
 * (max <= 0 means every remaining question).
 */
export const selectNextBatch = (allQuestions, progress, category, max) => {
    const remaining = getUnaudited(allQuestions, progress, category);
    return max > 0 ? remaining.slice(0, max) : remaining;
};

/**
 * Records one run for a category and returns a new progress object.
 * `auditedIds` must only contain ids from batches that actually succeeded -
 * ids from failed batches stay unaudited and are retried by the next run.
 * `allQuestions` is the category's current question list (after fixes), used
 * to compute the total and whether the category is now complete.
 */
export const recordRun = (progress, category, run, allQuestions) => {
    const next = normalizeProgress(progress);
    const entry = next.categories[category] || emptyCategory();
    const audited = new Set(entry.auditedIds);
    (run.auditedIds || []).forEach((id) => audited.add(id));

    const modifiedIds = run.modifiedIds || [];
    entry.auditedIds = [...audited];
    entry.total = allQuestions.length;
    entry.complete = allQuestions.every((q) => audited.has(q.id));
    entry.runs = [
        ...entry.runs,
        {
            runId: String(run.runId ?? 'local'),
            date: run.date,
            audited: (run.auditedIds || []).length,
            modified: modifiedIds.length,
            failedBatches: run.failedBatches || 0,
            modifiedIds,
        },
    ];
    next.categories[category] = entry;
    return next;
};

/**
 * Marks a category complete (or not) without recording a run - used when a run
 * finds nothing left to audit.
 */
export const refreshCompletion = (progress, category, allQuestions) => {
    const next = normalizeProgress(progress);
    const entry = next.categories[category] || emptyCategory();
    const audited = new Set(entry.auditedIds);
    entry.total = allQuestions.length;
    entry.complete = allQuestions.every((q) => audited.has(q.id));
    next.categories[category] = entry;
    return next;
};

/**
 * Human-readable summary table (audit/PROGRESS.md). `idsByCategory` maps every
 * category to the ids currently in its file, so counts ignore deleted questions.
 */
export const renderSummary = (progress, idsByCategory, generatedAt) => {
    const lines = [
        '# Audit progress',
        '',
        'Generated by `scripts/audit-category.mjs` after every audit run - do not edit by hand.',
        'Machine-readable source of truth: `audit/progress.json`.',
        '',
        `Last updated: ${generatedAt}`,
        '',
        '| Category | Questions | Audited | Remaining | Status | Last run |',
        '| :--- | ---: | ---: | ---: | :--- | :--- |',
    ];

    for (const category of Object.keys(idsByCategory).sort()) {
        const ids = idsByCategory[category];
        const entry = progress?.categories?.[category];
        const audited = new Set(entry?.auditedIds || []);
        const done = ids.filter((id) => audited.has(id)).length;
        const remaining = ids.length - done;
        const lastRun = entry?.runs?.length ? entry.runs[entry.runs.length - 1] : null;
        let status = 'not started';
        if (remaining === 0 && ids.length > 0) status = 'complete';
        else if (done > 0) status = 'in progress';
        lines.push(
            `| ${category} | ${ids.length} | ${done} | ${remaining} | ${status} | ${lastRun ? `${lastRun.date} (run ${lastRun.runId})` : '-'} |`
        );
    }
    lines.push('');
    return lines.join('\n');
};
